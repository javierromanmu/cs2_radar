/*
 * downloads missing maps from MurkyYT/cs2-map-icons (extracted from the game depot)
 * and writes them into public/data/<map>/ using the format the radar expects:
 *
 *   data.json       { x, y, scale, levels? }
 *   radar.png       main overview
 *   radar_<lvl>.png extra levels (nuke lower, vertigo lower...)
 *   background.png  page background
 *
 * usage:
 *   node scripts/sync-maps.js                 install maps that are not in public/data
 *   node scripts/sync-maps.js --only a,b      restrict to these maps
 *   node scripts/sync-maps.js --force         overwrite maps that already exist
 *   node scripts/sync-maps.js --dry-run       only print what would be done
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://raw.githubusercontent.com/MurkyYT/cs2-map-icons/main";
const DATA_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../public/data");
const FALLBACK_BACKGROUND = path.join(DATA_DIR, "de_dust2", "background.png");

const args = process.argv.slice(2);
const FORCE = args.includes("--force");
const DRY_RUN = args.includes("--dry-run");
const onlyIdx = args.indexOf("--only");
const ONLY = onlyIdx !== -1 ? args[onlyIdx + 1].split(",") : null;

const fileName = (url) => url.split("/").pop();

/* prefer the hand made psd radar, then the autogenerated tga, then the legacy name.
   hashed variants (de_x_radar_tga_ab12cd34) and spectate radars are ignored */
const findRadar = (radarPaths, prefix) => {
  for (const suffix of ["_radar_psd.png", "_radar_tga.png", "_radar.png"]) {
    const match = radarPaths.find((url) => fileName(url) === `${prefix}${suffix}`);
    if (match) return match;
  }
  return null;
};

const download = async (url) => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return Buffer.from(await response.arrayBuffer());
};

const exists = (p) => fs.access(p).then(() => true, () => false);

const installMap = async (name, map) => {
  const info = map.radar_info;
  const mainRadar = findRadar(map.radar_paths || [], name);

  if (!info || info.pos_x === undefined || !mainRadar) {
    return { name, status: "skipped", reason: "no radar or overview data upstream" };
  }

  const mapData = { x: info.pos_x, y: info.pos_y, scale: info.scale };
  const files = { "radar.png": mainRadar };

  /* every vertical section except "default" gets its own radar image */
  const levels = [];
  for (const [section, range] of Object.entries(info.verticalsections || {})) {
    if (section === "default") continue;

    const radar = findRadar(map.radar_paths, `${name}_${section}`);
    if (!radar) continue;

    const image = `radar_${section}.png`;
    files[image] = radar;
    levels.push({
      name: section,
      image,
      altitudeMin: range.AltitudeMin,
      altitudeMax: range.AltitudeMax,
    });
  }
  if (levels.length) mapData.levels = levels;

  if (DRY_RUN) return { name, status: "dry-run", mapData, files };

  const dir = path.join(DATA_DIR, name);
  await fs.mkdir(dir, { recursive: true });

  for (const [target, url] of Object.entries(files)) {
    await fs.writeFile(path.join(dir, target), await download(url));
  }

  /* keep an existing background, otherwise use the first in-game screenshot */
  const background = path.join(dir, "background.png");
  if (!(await exists(background))) {
    const thumbs = map.thumb_paths || [];
    const thumb = thumbs.find((url) => /_1_png\.png$/.test(url)) || thumbs[0];
    if (thumb) await fs.writeFile(background, await download(thumb));
    else await fs.copyFile(FALLBACK_BACKGROUND, background);
  }

  await fs.writeFile(path.join(dir, "data.json"), JSON.stringify(mapData, null, 2) + "\n");

  return { name, status: "installed", mapData };
};

const main = async () => {
  const { maps } = JSON.parse((await download(`${SOURCE}/data/available.json`)).toString());
  const installed = await fs.readdir(DATA_DIR);

  const results = [];
  for (const [name, map] of Object.entries(maps)) {
    if (ONLY && !ONLY.includes(name)) continue;
    if (!FORCE && installed.includes(name)) continue;

    try {
      results.push(await installMap(name, map));
    } catch (error) {
      results.push({ name, status: "error", reason: error.message });
    }
  }

  for (const result of results) {
    const detail = result.reason || (result.mapData?.levels ? `levels: ${result.mapData.levels.map((l) => l.name)}` : "");
    console.log(`${result.status.padEnd(9)} ${result.name.padEnd(18)} ${detail}`);
  }
};

main();
